import os
import io
import time
from pathlib import Path
from typing import Dict, Any, Optional

try:
    from reportlab.lib.pagesizes import letter
    from reportlab.lib import colors
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image as RLImage, HRFlowable
    from reportlab.lib.units import inch
    HAS_REPORTLAB = True
except ImportError:
    HAS_REPORTLAB = False

from app.core.config import settings
from app.utils.nifti_io import load_nifti_volume, get_2d_slice, render_slice_visualization

def generate_pdf_report(result_info: Dict[str, Any], output_path: str) -> str:
    """
    Generates a formal medical research summary PDF report for the segmentation result.
    """
    if not HAS_REPORTLAB:
        raise RuntimeError("ReportLab is required to compile research PDF reports.")

    pdf_path = Path(output_path)
    pdf_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(pdf_path),
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Heading1'],
        fontName='Helvetica-Bold',
        fontSize=20,
        textColor=colors.HexColor('#0F172A'),
        spaceAfter=4
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=10,
        textColor=colors.HexColor('#475569'),
        spaceAfter=12
    )
    section_heading = ParagraphStyle(
        'SectionHead',
        parent=styles['Heading2'],
        fontName='Helvetica-Bold',
        fontSize=12,
        textColor=colors.HexColor('#1E3A8A'),
        spaceBefore=10,
        spaceAfter=6
    )
    disclaimer_style = ParagraphStyle(
        'Disclaimer',
        parent=styles['Normal'],
        fontName='Helvetica-Oblique',
        fontSize=8,
        textColor=colors.HexColor('#DC2626'),
        spaceBefore=4,
        spaceAfter=4
    )
    body_style = ParagraphStyle(
        'Body',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        textColor=colors.HexColor('#1E293B'),
        leading=12
    )

    story = []

    # Title & Banner
    story.append(Paragraph("NeuroScan AI — Brain Tumor Volumetric Analysis", title_style))
    story.append(Paragraph("Research & Educational Prototype | Multimodal 3D MRI Segmentation", subtitle_style))
    story.append(HRFlowable(width="100%", thickness=1.5, color=colors.HexColor('#2563EB'), spaceAfter=10))

    # Prominent Disclaimer Alert Box
    disclaimer_text = (
        "<b>RESEARCH & EDUCATIONAL USE ONLY:</b> This automated quantitative report is generated by an experimental "
        "3D deep learning model. It is NOT clinical diagnostic software and must not be used to replace the diagnostic "
        "judgment of a qualified board-certified radiologist or neuro-oncologist. Volume estimations represent voxel "
        "approximations and may be subject to acquisition artifacts, motion, and intensity variations."
    )
    disclaimer_table = Table([[Paragraph(disclaimer_text, disclaimer_style)]], colWidths=[530])
    disclaimer_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#FEF2F2')),
        ('BOX', (0, 0), (-1, -1), 1, colors.HexColor('#F87171')),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    story.append(disclaimer_table)
    story.append(Spacer(1, 10))

    # Session & Scan Metadata
    quant = result_info.get("quantitative_report", {})
    metadata_data = [
        [
            Paragraph("<b>Analysis Session ID:</b>", body_style),
            Paragraph(result_info.get("result_id", "N/A"), body_style),
            Paragraph("<b>Generated Timestamp:</b>", body_style),
            Paragraph(result_info.get("created_at", time.strftime("%Y-%m-%d %H:%M")), body_style),
        ],
        [
            Paragraph("<b>Model Architecture:</b>", body_style),
            Paragraph("3D U-Net (BraTS Benchmark Config)", body_style),
            Paragraph("<b>Processing Time:</b>", body_style),
            Paragraph(f"{quant.get('processing_time_seconds', 0.0):.2f} seconds", body_style),
        ],
        [
            Paragraph("<b>Volume Dimensions:</b>", body_style),
            Paragraph(f"{result_info.get('dimensions', 'N/A')}", body_style),
            Paragraph("<b>Voxel Spacing:</b>", body_style),
            Paragraph(f"{result_info.get('voxel_spacing', 'N/A')} mm", body_style),
        ]
    ]

    meta_table = Table(metadata_data, colWidths=[120, 145, 120, 145])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor('#F8FAFC')),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor('#CBD5E1')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 12))

    # Quantitative Volumetric Table
    story.append(Paragraph("Quantitative Volumetric Analysis (BraTS Label Hierarchy)", section_heading))
    
    table_headers = ["Subregion", "BraTS Labels", "Voxel Count", "Volume (cm³)", "Axial Slices", "Lesion Count"]
    header_row = [Paragraph(f"<b>{h}</b>", body_style) for h in table_headers]
    table_rows = [header_row]

    for reg in quant.get("regions", []):
        row = [
            Paragraph(reg.get("region_name", "N/A"), body_style),
            Paragraph(str(reg.get("labels_included", [])), body_style),
            Paragraph(f"{reg.get('voxel_count', 0):,}", body_style),
            Paragraph(f"<b>{reg.get('volume_cm3', 0.0):.3f} cm³</b>", body_style),
            Paragraph(f"{reg.get('slice_extent_axial', [0, 0])}", body_style),
            Paragraph(str(reg.get("connected_components", 0)), body_style),
        ]
        table_rows.append(row)

    vol_table = Table(table_rows, colWidths=[150, 75, 75, 85, 75, 70])
    vol_table.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#E2E8F0')),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#94A3B8')),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
    ]))
    story.append(vol_table)
    story.append(Spacer(1, 14))

    # Quality Warnings
    warnings = quant.get("quality_warnings", [])
    if warnings:
        story.append(Paragraph("Quality Control & Processing Warnings", section_heading))
        for w in warnings:
            story.append(Paragraph(f"• {w}", body_style))
        story.append(Spacer(1, 10))

    # Multi-planar Slice Visualizations
    story.append(Paragraph("Multi-Planar Slice Visualizations (Axial, Coronal, Sagittal)", section_heading))
    try:
        mri_path = result_info.get("mri_path")
        mask_path = result_info.get("mask_path")
        if mri_path and mask_path and Path(mri_path).exists() and Path(mask_path).exists():
            mri_data, _, _ = load_nifti_volume(mri_path)
            mask_data, _, _ = load_nifti_volume(mask_path)
            
            # Find slice with maximum tumor in axial plane
            ax_tumor = np.sum(mask_data > 0, axis=(0, 1))
            best_ax = int(np.argmax(ax_tumor)) if np.max(ax_tumor) > 0 else mri_data.shape[2] // 2
            
            cor_tumor = np.sum(mask_data > 0, axis=(0, 2))
            best_cor = int(np.argmax(cor_tumor)) if np.max(cor_tumor) > 0 else mri_data.shape[1] // 2
            
            sag_tumor = np.sum(mask_data > 0, axis=(1, 2))
            best_sag = int(np.argmax(sag_tumor)) if np.max(sag_tumor) > 0 else mri_data.shape[0] // 2

            # Render slices to temp buffers
            from PIL import Image
            img_flows = []
            for plane, s_idx in [("axial", best_ax), ("coronal", best_cor), ("sagittal", best_sag)]:
                mri_2d = get_2d_slice(mri_data, plane, s_idx)
                mask_2d = get_2d_slice(mask_data, plane, s_idx)
                vis = render_slice_visualization(mri_2d, mask_2d)
                # Decode base64
                import base64
                b64_data = vis["overlay_base64"].split(",")[1]
                img_bytes = base64.b64decode(b64_data)
                img_io = io.BytesIO(img_bytes)
                rl_img = RLImage(img_io, width=2.4 * inch, height=2.4 * inch)
                img_flows.append([
                    rl_img,
                    Paragraph(f"<b>{plane.capitalize()} View</b> (Slice #{s_idx})", body_style)
                ])

            slice_table = Table([[img_flows[0][0], img_flows[1][0], img_flows[2][0]],
                                 [img_flows[0][1], img_flows[1][1], img_flows[2][1]]],
                                colWidths=[175, 175, 175])
            slice_table.setStyle(TableStyle([
                ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
            ]))
            story.append(slice_table)
    except Exception as e:
        story.append(Paragraph(f"Slice previews unavailable: {str(e)}", body_style))

    story.append(Spacer(1, 14))
    story.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor('#94A3B8'), spaceAfter=8))
    story.append(Paragraph(
        "<b>NeuroScan AI Medical Imaging Platform</b> | End-to-End Deep Learning Brain Tumor Volumetrics | "
        "Strictly for Investigation & Verification",
        body_style
    ))

    doc.build(story)
    return str(pdf_path)
